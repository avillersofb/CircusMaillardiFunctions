#' @title simulate_distri
#'
#' @description This function simulates values the distribution of the abundance index thanks to the approach proposed by Wood (2017).The abundance index is predicted from a GAM model, within thee same framework as the one used by Knape (2016), though this function includes the possibility to specify a grouping factor of interest (e.g. habitat type, cell id of a grid, etc). Simulated values are back-transformed using the inverse link function of the model family (e.g., exp for families using the log link functions, such as poisson, negative binomial or tweedie).
#'
#'
#' @param model A GAM model fitted with mgcv::gam() function, with ML or REML methods
#' @param dfpred A data.frame including a minima all the variables with which the model is fitted. A different grouping factor can also be specified, e.g. a habitat factor with 3 levels over within whichpredictions are to be estimated
#' @param time_var The name of the variable used to describe time, By default, 'year'
#' @param factor_name A grouping factor of interest, either used in the model or included in the dfpred *object*
#' @param nreplicates The number of values to be simulated, by default 1000
#' @importFrom mgcv predict.gam rmvn
#' @importFrom stats coef vcov
#' @return A list of simulated values, with the number of elements being equal to the number of levels of the grouping factor.
#' @references
#' Knape, J. (2016). Decomposing trends in Swedish bird populations using
#' generalized additive mixed models. Journal of Applied Ecology, 53(6), 1852-1861.
#' @export
#'
#'
simulate_distri<-function(model, dfpred, time_var="year", factor_name=NA, nreplicates=1000){


  #Check that the model was run with parameters estimated through REML
  if(!model$method %in% c("REML", "ML")) message("Predictions computed through this function are using the unconditionnal=T option of the vcov function: this requires models to be fitted with method=REML or ML")
  #Some information on the variables to properly index the resulting matrix

  #Need to check if the factor_name isn't included in the model parameters -> this will mess up the results matrix (this could happen when the objective is to predict over a grid for example (though X-Y), as one needs to keep track of the cell id


  Xp<-predict.gam(model, newdata=dfpred, type="lpmatrix") #
  betas_mod<-coef(model)
  vcov_mod<-vcov(model, unconditional=TRUE) #unconditional = T allows parameter estimates to be treated as uncertain at their estimates, but this requires the model to be estimated through REML or ML--> add some line of code to check that beforehand and throw a warning if needed)

  #sample MVN values of beta
  betas_rep<-rmvn(n=nreplicates, betas_mod, vcov_mod)

  #Product with the inverse link
  linkinv <- model$family$linkinv

  lp<-t(linkinv(Xp %*% t(betas_rep))) #



  #If there is a structuring factor, store the results in a list
  if(!is.na(factor_name)){
    #A list to store the results
    list_distri<-list()

    #Convert grouping factor if it is not
    if(!is.factor(dfpred[,factor_name])){
      dfpred[,factor_name]<-factor(dfpred[,factor_name])
    }

    #return the ids of each
    index_fact<-lapply(levels(dfpred[,factor_name]), function(x) which(dfpred[,factor_name]==x))

    for (i in 1:length(index_fact)){
      list_distri[[i]]<-lp[,index_fact[[i]], drop=FALSE]
      colnames(list_distri[[i]])<-dfpred[,time_var][index_fact[[i]]]
    }
    # names for each element of the list
    names(list_distri)<-levels(dfpred[,factor_name])

    #this list is returned as the basis to compute mean trend and confidene intervals
    return(list_distri)
  }
  else{ #if no structuring factor, then just name lp (with the year index) and return lp
    colnames(lp)<-dfpred[,time_var]
    return(lp)
  }

}


#' @title compute_trends
#'
#' @description This function computes trends of the abundance index thanks to the values simulated by the *simulate_distri()* function, and some grouping factor of interested.
#'
#'
#' @param list_distri The object generated by the *simulate_distri()* function (a list of values)
#' @param factor_name A grouping factor of interest (same as the one used with the *simulate_distri()* function
#' @param ystart First time point used to compute the trend
#' @param yend Last time point used to compute the trend
#' @param alpha Error threshold used to compute the confidence intervals, by default 5%
#' @importFrom stats quantile
#' @return A dataframe containing population trend expressed as a percentage between *ystart* and *yend*, with confidence intervals computed at the specified *alpha* value and for the levels of the grouping factor, if any
#' @export
#'
#'


compute_trends<-function(list_distri, factor_name=NA, ystart, yend, alpha = 0.05){

  ystart<-as.character(ystart)
  yend<-as.character(yend)
  perChange<-function(x) 100 * (x[,yend] - x[,ystart])/x[,ystart]


  if(!is.data.frame(list_distri)  && is.list(list_distri) && is.na(factor_name)){

    #merge distributions of values for the ystart & yend in 2 vectors
    l_sta_end<-lapply(list_distri, function(x) {
      x[,c(ystart,yend)]
    })

    df_sta_end<-do.call("rbind", l_sta_end)
    trT<- perChange(df_sta_end)
    CIT<-quantile(trT, probs = c(alpha/2, 1 - alpha/2), na.rm=T)
    mean_trT<-mean(trT)
    resT<-data.frame(mean_trend=mean_trT, CI_low=CIT[1], CI_high=CIT[2])

  }else if(!is.na(factor_name)){ #if there is a grouping factor
    resT<-lapply(list_distri, function(y) { #apply on the list
      trT<- perChange(y)
      CIT<-quantile(trT, probs = c(alpha/2, 1 - alpha/2), na.rm=TRUE)
      mean_trT<-mean(trT)
      resT<-data.frame(mean_trend=mean_trT, CI_low=CIT[1], CI_high=CIT[2])

    })
    resT<-do.call("rbind", resT)
    resT$id<-names(list_distri)
    resT<-resT[,c(4,1:3)]

  }else{
    trT<- perChange(list_distri)
    CIT<-quantile(trT, probs = c(alpha/2, 1 - alpha/2))
    mean_trT<-mean(trT)
    resT<-data.frame(mean_trend=mean_trT, CI_low=CIT[1], CI_high=CIT[2])


  }
  return(resT)
}

#' @title compute_abs_diff
#'
#' @description This function computes absolute differences in the abundance index used, thanks to the values simulated by the *simulate_distri()* function, and some grouping factor of interested.
#'
#'
#' @param list_distri The object generated by the *simulate_distri()* function (a list of values)
#' @param factor_name A grouping factor of interest (same as the one used with the *simulate_distri()* function
#' @param ystart First time point used to compute the trend
#' @param yend Last time point used to compute the trend
#' @param alpha Error threshold used to compute the confidence intervals, by default 5%
#' @importFrom stats quantile
#' @return A data.frame containing mean differences for the abundance index between *ystart* and *yend*, with confidence intervals computed at the specified *alpha* value and for the levels of the grouping factor, if any
#' @export
#'
#'

compute_abs_diff<-function(list_distri, factor_name=NA, ystart, yend, alpha = 0.05){

  ystart<-as.character(ystart)
  yend<-as.character(yend)
  absChange<-function(x) x[,yend] - x[,ystart]

  if(!is.na(factor_name)){ #if there is a grouping factor
    resT<-lapply(list_distri, function(y) {
      trT<- absChange(y)
      CIT<-quantile(trT, probs = c(alpha/2, 1 - alpha/2))
      mean_trT<-mean(trT)
      resT<-data.frame(mean_diff=mean_trT, CI_low=CIT[1], CI_high=CIT[2])

    })
    resT<-do.call("rbind", resT)
    resT$id<-names(list_distri)
    resT<-resT[,c(4,1:3)]

  }else{
    trT<- absChange(list_distri)
    CIT<-quantile(trT, probs = c(alpha/2, 1 - alpha/2))
    mean_trT<-mean(trT)
    resT<-cbind(mean_diff=mean_trT, CI_low=CIT[1], CI_high=CIT[2])


  }
  return(resT)
}


#' @title abund2ggplot
#'
#' @description This function converts the list of values returned by compute_distri so the results to be plotted readily by ggplot2 functions
#'
#'
#' @param list_distri The object generated by the *simulate_distri()* function (a list of values)
#' @param alpha Error threshold used to compute the confidence intervals, by default 5%
#' @return A data.frame that can be readily used to plot simulated values with ggplot2
#' @importFrom stats quantile
#' @export
#'
#'


#abundance to ggplot: transform the lists from the computed distri function
abund2ggplot<-function(list_distri, alpha=0.05){

  if (is.matrix(list_distri)) list_distri <- list(all = list_distri)

  temp<-lapply(list_distri, function(x) {


    lT<-apply(x, 2, function(y){

      mean<-mean(y)
      CIs<-quantile(y, probs = c(alpha/2, 1 - alpha/2))
      return(rbind(mean, CIs[1], CIs[2]))
    }
    )
  }
  )
  tempdf<-lapply(temp, function(z) {
    dfT<-data.frame(t(z))
    return(dfT)
  }
  )

  tempr<-do.call("rbind", tempdf)
  tempr$year<-as.numeric(dimnames(list_distri[[1]])[[2]])
  tempr$factor_id<- rep(names(list_distri), each=dim(list_distri[[1]])[2])
  names(tempr)[1:3]<-c("mean", "CI_low", "CI_high")
  return(tempr)



}

#' @title extract_CI_sp_correl
#'
#'@description
#' This function extracts values of objects created with from ncf::spline.correlog() (x, y, confidence intervals) in order to customize spline correlograms with ggplot2

#' @param sp_corr_obj an object created with ncf::spline.correlog()
#' @return A data frame with columns x, y, ic_low and ic_high are returned.
#' @export
#' @examples
#' if (requireNamespace("ncf", quietly = TRUE) && requireNamespace("ggplot2", quietly = TRUE)) {
#'   x <- expand.grid(1:20, 1:5)[, 1]
#'   y <- expand.grid(1:20, 1:5)[, 2]
#'   # z data from an exponential random field
#'   z <- ncf::rmvn.spa(x = x, y = y, p = 1, method = "exp")
#'   fit1 <- ncf::spline.correlog(x = x, y = y, z = z, resamp = 100)
#'   df2ggplot2 <- extract_CI_sp_correl(fit1)
#'   ggplot2::ggplot(df2ggplot2) +
#'     ggplot2::geom_line(ggplot2::aes(x = x, y = y)) +
#'     ggplot2::geom_ribbon(ggplot2::aes(x = x, ymin = ic_low, ymax = ic_high),
#'                          alpha = 0.3, fill = "red")
#' }

extract_CI_sp_correl<-function(sp_corr_obj){

  dat.boot<-sp_corr_obj$boot$boot.summary$predicted
  dat.real<-sp_corr_obj$real$predicted

  x<-as.vector(dat.real$x)
  y<-as.vector(dat.real$y)
  ic_low<-dat.boot$y["0.025",]
  ic_high<-dat.boot$y["0.975",]
  df_fin<-data.frame(x=x, y=y, ic_low=ic_low, ic_high=ic_high)
  return(df_fin)
}


